const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const installer = require('./install-mock.cjs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    return ['krillion.io','www.krillion.io','party.krillion.io'].includes(url.hostname) ? route.continue() : route.abort();
  });
  context.setDefaultTimeout(15000);
  await context.addInitScript({content:installer()});
  const page = await context.newPage(), errors=[];
  page.on('pageerror', error => errors.push(error.message));
  let submits=0;
  page.on('request', request => { if (/\/submit$/.test(new URL(request.url()).pathname)) submits++; });
  await page.goto('https://krillion.io/',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'▼ BEGIN DESCENT ▼',exact:true}).click({force:true});
  const input=page.locator('input[aria-label="Your answer"]');
  await input.waitFor();
  const helper=page.locator('#krillion-io-tab-helper');
  await helper.locator('.candidate').first().waitFor();
  await page.waitForFunction(()=>document.querySelector('#krillion-io-tab-helper').shadowRoot.querySelector('.candidate small')?.textContent.includes('100 · sheet')); 
  const top=await helper.locator('.candidate').first().innerText();
  assert.match(top,/100 · sheet/);
  await input.focus();await input.press('Tab');
  const first=await input.inputValue(); assert(first);
  assert(await page.locator('.ds-dive-btn').isEnabled(),'Native React state must update');
  await input.press('Tab');const second=await input.inputValue();assert.notEqual(first,second);
  await input.press('Shift+Tab');assert.equal(await input.inputValue(),first);
  const prefix=first.slice(0,Math.min(5,first.length));
  await input.fill(prefix);await input.press('Tab');assert((await input.inputValue()).toLowerCase().startsWith(prefix.toLowerCase()));
  await input.press('Escape');await helper.locator('section').waitFor({state:'hidden'});
  await input.press('Tab');await helper.locator('section').waitFor({state:'visible'});
  assert.equal(submits,0,'Completion must not submit answers');
  console.log('PASS live Daily: full catalog, actual score sorting, React input, prefix, Tab/reverse, Escape, no auto-submit.');

  const pufferContext=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await pufferContext.route('**/*',route=>['krillion.io','party.krillion.io'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
  pufferContext.setDefaultTimeout(15000);
  await pufferContext.addInitScript({content:installer('window.WebSocket = class extends EventTarget { constructor(url) { super(); this.url=url; } send() {} close() {} };')});
  const puffer=await pufferContext.newPage();
  puffer.on('pageerror',error=>errors.push(error.message));
  const send = async data => puffer.evaluate(value=>window.testSocket.dispatchEvent(new MessageEvent('message',{data:JSON.stringify(value)})),data);
  await puffer.goto('https://krillion.io/party/KRLP?preview=round',{waitUntil:'domcontentloaded'});
  const partyInput=puffer.locator('input[aria-label="Your answer"]');await partyInput.waitFor();
  const partyHelper=puffer.locator('#krillion-io-tab-helper');await partyHelper.locator('.candidate').first().waitFor();
  assert.match(await partyHelper.locator('.candidate').first().innerText(),/Haminados.*100 · daily sample/s);
  await partyInput.focus();await partyInput.press('Tab');assert.equal(await partyInput.inputValue(),'Haminados');
  assert.equal(await partyInput.getAttribute('maxlength'),'60');
  await partyInput.fill('');
  // Native constructor replaced with local EventTarget before helper injection: no room connection.
  await puffer.evaluate(()=>{window.testSocket=new WebSocket('wss://party.krillion.io/rooms/KRLP/ws');});
  const room={code:'KRLP',gameId:'fixture-1',version:1,phase:'round',category:{index:2,text:'Name a way to prepare eggs',accepted:1},events:[{seq:1,kind:'category',index:2},{seq:2,kind:'pass',answer:'Haminados',tier:'krillion'}]};
  await send({t:'snap',room});
  await puffer.waitForTimeout(150);
  assert(!(await partyHelper.locator('.candidate').allTextContents()).some(text=>text.includes('Haminados')),'Observed used answer must disappear');
  await send({t:'patch',patch:{base:1,v:2,now:Date.now(),set:{category:{index:3,text:'Name a way to prepare eggs',accepted:0}},events:[{seq:3,kind:'category',index:3}]}});
  await puffer.waitForTimeout(150);
  assert.match(await partyHelper.locator('.candidate').first().innerText(),/Haminados.*100 · Puffer ✓/s);
  // Unrelated live patches must not destroy original Tab query/candidate cycle.
  await partyInput.focus();await partyInput.press('Tab');const beforePatch=await partyInput.inputValue();
  await send({t:'patch',patch:{base:2,v:3,now:Date.now(),players:[{id:'fixture',typing:'anything'}]}});
  await puffer.waitForTimeout(80);await partyInput.press('Tab');
  assert.notEqual(await partyInput.inputValue(),beforePatch,'Tab cycle survives unrelated Puffer traffic');
  const saved=await puffer.evaluate(()=>JSON.parse(localStorage.getItem('krillion-io-tab:v2')));
  assert.equal(saved.learned['name a way to prepare eggs'].haminados[1],'krillion');
  assert(!JSON.stringify(saved).includes('fixture-1'),'Do not persist room identities');
  const chat=puffer.getByRole('textbox',{name:'Chat message',exact:true});
  if(await chat.count()){
    await chat.fill('hello');await chat.focus();
    const intercepted=await chat.evaluate(element=>{const event=new KeyboardEvent('keydown',{key:'Tab',bubbles:true,cancelable:true});element.dispatchEvent(event);return event.defaultPrevented;});
    assert.equal(intercepted,false,'Chat Tab must not be intercepted');
  }
  console.log('PASS Puffer fixture + mocked socket: sampled bank, exact-category match, input limit, snapshots, patch transitions, used exclusions, verified tier learning, category reset, chat isolation.');
  assert.deepEqual(errors,[],'Browser should have no page errors');
  await partyInput.fill('');
  await puffer.locator('.ds-card:not(.pf-newcat) .prompt').last().evaluate(element=>{element.textContent='Name a mystery test mineral';});
  await puffer.waitForFunction(()=>document.querySelector('#krillion-io-tab-helper').shadowRoot.querySelector('.candidate small')?.textContent.includes('AI guess ?'));
  assert.match(await partyHelper.locator('.candidate').first().innerText(),/Painite.*\? · AI guess \?/s);
  await partyInput.focus();await partyInput.press('Tab');assert.equal(await partyInput.inputValue(),'Painite');
  const aiRequests=await puffer.evaluate(()=>window.__aiTestRequests);
  assert.equal(aiRequests.length,1,'One automatic request per unknown category, not per keystroke');
  assert.equal(aiRequests[0].model,'dots-studio/dots-3-note-preview:free');
  assert.equal(aiRequests[0].reasoning.enabled,false);
  assert(!JSON.stringify(await puffer.evaluate(()=>({...localStorage}))).includes('sk-or-'),'No API key in game storage');
  assert.deepEqual(errors,[],'AI integration should have no page errors');
  console.log('PASS browser AI: unknown-category automatic fallback, unverified/no-score labels, Tab fill, one request, no key in game localStorage. Requests mocked; no real OpenRouter API key used.');
  await puffer.screenshot({path:'/tmp/krillion-puffer-helper-verified.png'});
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
